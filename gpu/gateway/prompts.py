"""Промпты. Версионируются здесь, а не расползаются по вызывающим сервисам.

Главное правило всего файла — ПОРЯДОК. Схема и инструкции живут в системном
сообщении и не меняются никогда; диалог живёт в пользовательском и только
дописывается в хвост. Отсюда сразу две вещи:

  * prefix cache vLLM попадает почти целиком — префилл падает с ~1200 токенов
    на ход до ~30, то есть в 40 раз. Без этого одна карта не вывозит даже пилот;
  * исчезает нестабильность от перестановки фактов (у 9B измерено 14% смены
    вердикта при жадном декодировании) — переставлять становится нечего.

Любая правка, которая начнёт пересобирать или переупорядочивать историю
диалога между ходами, ломает и то и другое одновременно и молча.
"""
import json

from .vendor.extraction_schema import JSON_SCHEMA, LIFE_SITUATIONS, CATEGORIES, MUNICIPALITIES

PROMPT_VERSION = "extract/v1"

# --- извлечение фактов -------------------------------------------------------

SYSTEM_EXTRACT = """Ты разбираешь расшифровку живого разговора в окне МФЦ.
Говорят двое: оператор и посетитель. Разметки, кто именно говорит, НЕТ —
определяй по смыслу реплики.

Верни JSON строго по схеме. Ничего кроме JSON.

ПРАВИЛА
1. Факты берутся ТОЛЬКО из утверждений посетителя о себе.
   Вопрос — не факт. «У вас двое детей?» задаёт оператор: это не значит,
   что у посетителя двое детей. Факт появляется, когда посетитель ответил.
2. Значения перечислимых полей — дословно из списков ниже. Ничего не
   переводи, не сокращай и не придумывай своих формулировок.
3. Чего в разговоре нет — null или пустой список. Не домысливай.
4. intents: 1-4 коротких формулировки того, зачем человек пришёл, по 3-8 слов,
   деловым языком без канцелярита. Главное — первым. Если из разговора следуют
   разные услуги, перечисли все, не выбирай одну.
5. unresolved: чего оператор ещё не спросил, но без этого услугу не выбрать.

СХЕМА
{schema}

life_situation — одно из: {life}
categories — из: {cats}
municipality — муниципальное образование Тульской области: {munis}
""".format(
    schema=json.dumps(JSON_SCHEMA, ensure_ascii=False, indent=1),
    life=", ".join(LIFE_SITUATIONS),
    cats=", ".join(CATEGORIES),
    munis=", ".join(MUNICIPALITIES),
)

_ROLE = {"client": "посетитель", "operator": "оператор", None: "?"}


def render_dialog(turns):
    """Реплики в хронологии, по одной на строку. ТОЛЬКО дописывание.

    Роль печатается, если она известна: диаризации сейчас нет и приходит null,
    но контракт её допускает, и когда она появится, промпт менять не придётся.
    """
    lines = []
    for t in turns:
        role = _ROLE.get(t.get("speaker"), "?")
        lines.append(f"[{t['seq']}] {role}: {t['text'].strip()}")
    return "\n".join(lines)


def extract_messages(turns):
    return [{"role": "system", "content": SYSTEM_EXTRACT},
            {"role": "user", "content": render_dialog(turns)}]


# --- вопрос оператора по документу -------------------------------------------

SYSTEM_ASK = """Ты помогаешь оператору МФЦ разобраться в регламенте одной услуги.

Отвечай ТОЛЬКО тем, что написано в документе ниже.
Каждое утверждение подкрепляй дословной цитатой из документа в «кавычках-ёлочках».
Чего в документе нет — отвечай «в регламенте не указано» и не догадывайся.
Не пересказывай весь документ: отвечай на заданный вопрос, коротко и по делу.
Оператор читает твой ответ вслух посетителю, поэтому пиши живым языком,
а канцелярит оставляй только внутри цитат."""


def ask_messages(document, question, history=None):
    """Документ идёт РАНЬШЕ истории и вопроса — он стабилен, значит кэшируется.

    Второй вопрос по той же карточке стоит примерно вдесятеро дешевле первого:
    2-3 тысячи токенов регламента уже лежат в prefix cache.
    """
    doc = "\n\n".join(f"## {k}\n{v}" for k, v in document.items() if v and str(v).strip())
    msgs = [{"role": "system", "content": SYSTEM_ASK},
            {"role": "user", "content": f"ДОКУМЕНТ УСЛУГИ\n\n{doc}"},
            {"role": "assistant", "content": "Документ прочитан. Задавайте вопрос."}]
    for h in (history or []):
        if h.get("role") in ("user", "assistant") and h.get("content"):
            msgs.append({"role": h["role"], "content": h["content"]})
    msgs.append({"role": "user", "content": question})
    return msgs


