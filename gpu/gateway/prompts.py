# Русские заголовки сырых полей выгрузки: модель хуже ищет ответ в секции
# «documentsText», чем в «Документы». Ключи словаря при этом не меняются —
# смещения цитат core-api считает по ним же.
SECTION_LABELS = {
    "serviceTitleText": "Название услуги",
    "serviceRecipients": "Кому положено",
    "documentsText": "Документы",
    "serviceResultText": "Результат оказания услуги",
    "rejectReasonsText": "Основания для отказа",
    "timeTermText": "Сроки предоставления",
    "paymentInfoText": "Стоимость и порядок оплаты",
    "serviceOrderingText": "Порядок подачи заявления",
}


def ask_messages(document, question, history=None):
    """Документ идёт РАНЬШЕ истории и вопроса — он стабилен, значит кэшируется.

    Второй вопрос по той же карточке стоит примерно вдесятеро дешевле первого:
    2-3 тысячи токенов регламента уже лежат в prefix cache.
    """
    def label(key):
        return SECTION_LABELS.get(key, key)

    doc = "\n\n".join(f"## {label(k)}\n{v}" for k, v in document.items() if v and str(v).strip())
    msgs = [{"role": "system", "content": SYSTEM_ASK},
            {"role": "user", "content": f"ДОКУМЕНТ УСЛУГИ\n\n{doc}"},
            {"role": "assistant", "content": "Документ прочитан. Задавайте вопрос."}]
    for h in (history or []):
        if h.get("role") in ("user", "assistant") and h.get("content"):
            msgs.append({"role": h["role"], "content": h["content"]})
    msgs.append({"role": "user", "content": question})
    return msgs


