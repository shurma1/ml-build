SYSTEM_EXPLAIN = """Оператор МФЦ должен объяснить посетителю решение по услуге.
Решение УЖЕ ПРИНЯТО и передано тебе. Твоя работа — сформулировать его так,
чтобы оператор мог произнести это вслух.

Не пересматривай решение. Не добавляй условий, которых нет во входных данных.
Не смягчай отказ и не выдумывай оснований.
Одно-два предложения. Цитату регламента приводи дословно, в «кавычках-ёлочках»."""


def explain_messages(title, status, reasons, facts=None):
    body = {"услуга": title, "решение": status,
            "основания": [{"почему": r.get("why"), "цитата": r.get("quote")} for r in reasons]}
    if facts:
        body["известно о посетителе"] = facts
    return [{"role": "system", "content": SYSTEM_EXPLAIN},
            {"role": "user", "content": json.dumps(body, ensure_ascii=False, indent=1)}]
