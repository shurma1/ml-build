# -*- coding: utf-8 -*-
"""Единственное, что осталось от идеи «не звать LLM на каждую реплику».

Гейт по содержанию реплики измерен и отвергнут: на эталоне из 132 реплик он ловил
63% информативных, то есть терял 37% фактов, экономя 47% вызовов. Это неприемлемо —
LLM зовём на каждой реплике.

Здесь остаётся только то, что безопасно:
  * отсев пустых и чисто служебных сегментов VAD (в них нечего извлекать);
  * ограничитель одновременных вызовов — по области 383 окна, при 30% загрузки
    это ~52 параллельных запроса к 9B, и очередь нужна явная, а не стихийная.
"""
import asyncio, re, time

# Сегменты, в которых нет ни одного содержательного слова. Короткие аббревиатуры
# (ИП, СВО, ЕГРН) содержательны — отсекать по длине слова нельзя.
_FILLER = set('''да нет ага угу ну вот так это тут там значит понятно хорошо ладно
конечно спасибо здравствуйте пожалуйста извините секунду минуту подождите сейчас
слушаю говорите ясно окей ок алло э м мм эм'''.split())
_SHORT_OK = {'ип', 'ооо', 'сво', 'вбд', 'мфц', 'инн', 'снилс', 'егрн', 'егрип',
             'егрюл', 'чаэс', 'ижс', 'птс', 'загс', 'епгу', 'жкх'}


def is_empty_segment(text):
    """True, если извлекать из сегмента нечего. Единственный безопасный фильтр."""
    ws = re.findall(r'[а-яёa-z0-9]+', (text or '').lower().replace('ё', 'е'))
    return not [w for w in ws if w not in _FILLER and (len(w) > 2 or w in _SHORT_OK)]


class CallLimiter:
    """Явная очередь к LLM: ограничивает параллельность и отбрасывает устаревшие
    сегменты того же диалога — пока запрос ждал, клиент уже сказал следующее."""

    def __init__(self, max_concurrent=32, stale_after=6.0):
        self.sem = asyncio.Semaphore(max_concurrent)
        self.stale_after = stale_after
        self.latest = {}

    async def run(self, session_id, coro_factory):
        seq = self.latest[session_id] = self.latest.get(session_id, 0) + 1
        queued = time.monotonic()
        async with self.sem:
            if self.latest.get(session_id) != seq:
                return None                       # диалог ушёл вперёд — ответ не нужен
            if time.monotonic() - queued > self.stale_after:
                return None                       # очередь длиннее, чем пауза в речи
            return await coro_factory()
