"""Structured facets pulled out of a free-text query. Pure Python, ~0.05 ms.

Municipality is the only strongly selective facet in this corpus (26 values on
445 of 732 cards). Everything else — branch, recipient — barely filters anything
(by_branch: every branch offers ~700 of 732 services).
"""
import re
from nltk.stem.snowball import SnowballStemmer

_ST = SnowballStemmer('russian')

# Unambiguous place roots.
STRONG = {
    'город Тула': ['тул', 'тульск'],
    'город Алексин': ['алексин', 'алексинск'],
    'город Донской': ['донск', 'донско'],
    'город Ефремов': ['ефремов'],
    'город Новомосковск': ['новомосковск', 'новомосков'],
    'р.п. Новогуровский': ['новогуров', 'новогуровск'],
    'Арсеньевский район': ['арсеньев', 'арсеньевск'],
    'Белевский район': ['белев', 'белевск'],
    'Богородицкий район': ['богородиц', 'богородицк'],
    'Веневский район': ['венев', 'веневск'],
    'Воловский район': ['воловск'],
    'Дубенский район': ['дубен', 'дубенск'],
    'Заокский район': ['заок', 'заокск'],
    'Каменский район': ['каменск'],
    'Кимовский район': ['кимов', 'кимовск'],
    'Киреевский район': ['киреев', 'киреевск'],
    'Куркинский район': ['куркин', 'куркинск'],
    'Одоевский район': ['одоев', 'одоевск'],
    'Плавский район': ['плавск'],
    'Суворовский район': ['суворовск'],
    'Тепло-Огаревский район': ['теплоогарев', 'теплоогаревск', 'огарев'],
    'Узловский район': ['узловск', 'узлов'],
    'Чернский район': ['чернск'],
    'Щекинский район': ['щекин', 'щекинск'],
    'Ясногорский район': ['ясногор', 'ясногорск'],
}
# Roots that collide with ordinary words ("чёрный", "плавание", "каменный"):
# only accepted when a locality cue is present in the query.
WEAK = {
    'Воловский район': ['волов'], 'Каменский район': ['камен'], 'Плавский район': ['плав'],
    'Суворовский район': ['суворов'], 'Чернский район': ['черн'], 'город Ефремов': ['ефрем'],
    'р.п. Славный': ['славн'],      # «славно платят», «на славу»
}
# Признак топонима рядом: без него слабые корни не принимаются.
#
# У прежней версии не было правой границы, и короткие альтернативы срабатывали
# ВНУТРИ обычных слов: «мо» в «могилу», «можно», «мой»; «гор» в «горячим»,
# «гораздо», «горе». Признак получался истинным почти всегда, таблица WEAK
# работала как STRONG, и защита от ложных муниципалитетов не работала вовсе.
# Длинные формы склоняются (район/района/районе), короткие обязаны быть
# отдельным словом.
CUE = re.compile(
    r'(?<![а-яё])(?:'
    r'район\w*|город\w*|округ\w*|пос[её]л\w*|муниципальн\w*|администрац\w*|адм\.'
    r')(?![а-яё])'
    r'|(?<![а-яё])(?:р-н|рн|рп|мо)(?![а-яё])'
    r'|(?:р\.п\.|г\.|мо\.)')


def find_municipality(q):
    """-> canonical municipality name, or None when the query is region-wide/ambiguous."""
    ql = q.lower().replace('ё', 'е')
    ql = re.sub(r'тульск\w*\s+(обл\w*|региона?\w*)', ' ', ql)   # oblast != city of Tula
    toks = [_ST.stem(w) for w in re.findall(r'[а-яa-z]{3,}', ql)]
    hits = []

    def probe(table):
        # Только прямой префикс: токен запроса начинается с корня таблицы.
        # Обратное направление (корень начинается с токена) отсюда убрано: оно
        # сопоставляло 'чернск' с токеном 'черн' из «чёрный» и 'каменск' с
        # 'камен' из «каменная», обходя таблицу WEAK — а она заведена ровно
        # против этих слов. Короткие формы в таблицах уже есть отдельными
        # корнями ('щекин' рядом с 'щекинск'), так что терять нечего.
        for name, stems in table.items():
            for st in stems:
                if st in toks or any(t.startswith(st) and len(t) - len(st) <= 3
                                     for t in toks):
                    hits.append((len(st), name)); break

    probe(STRONG)
    if not hits and CUE.search(ql):
        probe(WEAK)
    if not hits:
        return None
    best = max(h[0] for h in hits)
    top = {n for l, n in hits if l == best}
    return top.pop() if len(top) == 1 else None


_RECIP = [(re.compile(r'(?<![а-я])(ип|индивидуальн\w* предпринимател\w*|самозанят\w*)'), 'ip'),
          (re.compile(r'(?<![а-я])(ооо|юр\w* лиц\w*|организац\w*|компани\w*|предприяти\w*)'), 'organization')]


def find_recipient(q):
    for rx, v in _RECIP:
        if rx.search(q.lower()):
            return v
    return None


# Необязательная вставка между «мне» и числом: живая речь и ASR редко дают
# чистое «мне N лет» — чаще «мне уже десять лет».
_FILLER = r'(?:(?:уже|сейчас|ровно|всего|лишь|только)\s+)?'
_AGE = re.compile(
    r'(?<![а-яё])мне\s+' + _FILLER + r'(\d{1,3})\s*(?:год(?:а|у)?|лет)\b',
    re.I,
)

# Словесные числительные в именительном падеже — ровно та форма, которая
# звучит после «мне» («мне двадцать три года»). Склонениями не занимаемся:
# это запасной путь для разового поиска без LLM, а не основной извлекатель.
_WNUM = {
    'ноль': 0, 'один': 1, 'одна': 1, 'два': 2, 'две': 2, 'двое': 2,
    'три': 3, 'трое': 3, 'четыре': 4, 'четверо': 4, 'пять': 5, 'шесть': 6,
    'семь': 7, 'восемь': 8, 'девять': 9, 'десять': 10, 'одиннадцать': 11,
    'двенадцать': 12, 'тринадцать': 13, 'четырнадцать': 14, 'пятнадцать': 15,
    'шестнадцать': 16, 'семнадцать': 17, 'восемнадцать': 18, 'девятнадцать': 19,
    'двадцать': 20, 'тридцать': 30, 'сорок': 40, 'пятьдесят': 50,
    'шестьдесят': 60, 'семьдесят': 70, 'восемьдесят': 80, 'девяносто': 90,
    'сто': 100,
}
_AGE_WORDS = re.compile(
    r'(?<![а-яё])мне\s+' + _FILLER + r'([а-яё]+(?:\s+[а-яё]+)?)\s*(?:год(?:а|у)?|годик\w*|лет)\b',
    re.I,
)


def find_age(q):
    """-> возраст в годах или None. Только «мне N лет», не «14-летнего» из регламента.

    Понимает и цифры, и слова («мне десять лет» -> 10): ASR отдаёт числительные
    текстом, и разовый поиск без LLM терял возраст целиком. Словесная форма
    проверяется по словарю ПОСЛОВНО — «мне нравится этот лет…» возрастом не станет.
    """
    q = q or ''
    m = _AGE.search(q)
    if m:
        n = int(m.group(1))
        return n if 0 <= n <= 120 else None
    m = _AGE_WORDS.search(q)
    if not m:
        return None
    vals = [_WNUM.get(w) for w in m.group(1).lower().split()]
    if not vals or any(v is None for v in vals):
        return None
    n = sum(vals)                                # «двадцать три» -> 20 + 3
    return n if 0 <= n <= 120 else None
