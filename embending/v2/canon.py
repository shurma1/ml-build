# -*- coding: utf-8 -*-
"""Канонизация: одинаковый смысл с разным написанием -> одна форма.

Три уровня, каждый проверяется отдельно — эффект у них разный:
  1. merge  — внутри группы дубликатов берём не «представителя», а модальный
              и самый полный вариант каждого поля по всей группе;
  2. spell  — нормализация написаний («техобслуживание» = «техническое обслуживание»,
              «р.д.» = «рабочих дней»), важна для лексического канала, где матч точный;
  3. strip  — снятие шаблонных фраз по document frequency. ОСТОРОЖНО: в корпусе из
              318 услуг фраза в 13% документов может быть определяющей для одной из них
              («паспорт гражданина Российской Федерации»). Список исключений обязателен.
"""
import re, collections

# --- 2. нормализация написаний -------------------------------------------
SPELL = [
    (r'(?i)\bр\.?\s?д\.?(?![а-я])', 'рабочих дней'),
    (r'(?i)\bк\.?\s?д\.?(?![а-я])', 'календарных дней'),
    (r'(?i)\bтехобслуживани\w*', 'техническое обслуживание'),
    (r'(?i)\bвдго\b', 'внутридомовое газовое оборудование'),
    (r'(?i)\bвкго\b', 'внутриквартирное газовое оборудование'),
    (r'(?i)\bмногофункциональн\w+ центр\w*( предоставления \w+ и \w+ услуг)?', 'МФЦ'),
    (r'(?i)\bединый портал государственных и муниципальных услуг\b', 'ЕПГУ'),
    (r'(?i)\bрегиональный портал государственных и муниципальных услуг\b', 'РПГУ'),
    (r'(?i)\bобъект\w* капитального строительства', 'объект капитального строительства'),
    (r'(?i)\bиндивидуальн\w+ жилищн\w+ строительств\w*', 'ИЖС'),
    (r'(?i)\bмногоквартирн\w+ дом\w*', 'многоквартирный дом'),
    (r'(?i)\bземельн\w+ участк\w*', 'земельный участок'),
    (r'(?i)\bжил\w+ помещени\w*', 'жилое помещение'),
    (r'(?i)\bденежн\w+ выплат\w*', 'денежная выплата'),
    (r'(?i)\bсоциальн\w+ поддержк\w*', 'социальная поддержка'),
    (r'(?i)\bспециальн\w+ военн\w+ операци\w*', 'СВО'),
    (r'(?i)\bветеран\w* боевых действий', 'ВБД'),
    (r'(?i)\bдокумент\w*,? удостоверяющ\w+ личность( заявителя)?', 'документ удостоверяющий личность'),
    (r'(?i)\bроссийск\w+ федерац\w+', 'Российская Федерация'),
]

# --- 3. шаблон, который безопасно снимать --------------------------------
# только канцелярские связки; всё, что может быть содержанием услуги, сюда не попадает
STRIP = [
    r'(?i)в соответствии с (нормативными правовыми актами|законодательством)[^.;\n]{0,60}',
    r'(?i)в порядке,? установленном[^.;\n]{0,60}',
    r'(?i)исчерпывающий перечень документов,? необходимых[^.;\n]{0,80}',
    r'(?i)(является|являются) (результатом|основанием) предоставления[^.;\n]{0,40}',
    r'(?i)для предоставления (государственной|муниципальной) услуги',
    r'(?i)(государственная|муниципальная) услуга предоставляется',
    r'(?i)\(при (наличии|обращении)[^)]{0,40}\)',
    r'(?i)в том числе в письменной форме',
]
# ...но не там, где фраза и есть смысл услуги
STRIP_EXEMPT = re.compile(r'(?i)паспорт|удостоверени|свидетельств|справк')


def spell(s):
    for rx, to in SPELL:
        s = re.sub(rx, to, s or '')
    return re.sub(r'\s+', ' ', s).strip()


def strip_boiler(s):
    if not s:
        return s
    for rx in STRIP:
        s = re.sub(rx, ' ', s)
    return re.sub(r'\s{2,}', ' ', s).strip(' ,;')


# --- 1. модальный и самый полный вариант поля по группе -------------------
_PLACE = re.compile(r'(?i)\b(муниципальн\w+ образовани\w+|администрац\w+)\b')

def _key(s):
    s = _PLACE.sub(' ', (s or '').lower())
    return ' '.join(sorted(set(w for w in re.findall(r'[а-яё]{4,}', s))))


def merge_field(values):
    """Из N редакций одного и того же — модальная формулировка, внутри неё самая полная."""
    vals = [v for v in values if v and v.strip()]
    if not vals:
        return ''
    groups = collections.defaultdict(list)
    for v in vals:
        groups[_key(v)].append(v)
    best = max(groups.values(), key=lambda g: (len(g), max(len(x) for x in g)))
    return max(best, key=len)


def canonical_type(t, level='merge'):
    """t — тип из build_types. Возвращает (who, result, docs) в канонической форме."""
    inst = t['instances']
    if level == 'none':
        return t['who'], t['result'], t['docs']
    who = merge_field([c['who'] for c in inst])
    res = merge_field([c['result'] for c in inst])
    doc = merge_field([c['docs'] for c in inst])
    if level in ('spell', 'strip'):
        who, res, doc = spell(who), spell(res), spell(doc)
    if level == 'strip':
        who, res, doc = (x if STRIP_EXEMPT.search(x or '') else strip_boiler(x)
                         for x in (who, res, doc))
    return who, res, doc


# --- структурные поля (для фильтров и ответов, не для поиска) -------------
def term_days(s):
    """Срок в рабочих днях. None, если не распознан однозначно."""
    if not s:
        return None
    s = spell(s).lower()
    m = re.search(r'(\d{1,3})\s*рабочих дней', s)
    if m:
        return int(m.group(1))
    m = re.search(r'(\d{1,3})\s*календарных дней', s)
    if m:
        return round(int(m.group(1)) * 5 / 7)
    return None


def is_free(s):
    if not s:
        return None
    return bool(re.search(r'(?i)бесплатн', s)) and not re.search(r'\d[\d\s]{2,}\s*руб', s)
