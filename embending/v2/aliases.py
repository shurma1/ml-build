import json as _json, os as _os

_GEN_PATH = _os.path.join(_os.path.dirname(_os.path.abspath(__file__)),
                          'eval', 'aliases_generated.jsonl')
_GEN = None


def _load_generated():
    """«Простые названия» услуги, сгенерированные LLM оффлайн по одному разу на тип.

    Замерено на 690 запросах: +5.2 п.п. R@1 (0.680 -> 0.732), причём прирост больше
    на срезе запросов, не имеющих общих слов с официальным названием (+6.0 против +4.3).
    Рукописная таблица DOC_ALIASES из двух десятков шаблонов давала -0.8 п.п. — дело
    не в идее, а в покрытии: нужны все 318 типов, а не популярные случаи.
    """
    global _GEN
    if _GEN is None:
        _GEN = {}
        if _os.path.exists(_GEN_PATH):
            for line in open(_GEN_PATH, encoding='utf-8'):
                d = _json.loads(line)
                _GEN[d['type_key']] = d['aliases']
    return _GEN


def doc_aliases_for(title, type_key=None):
    """Синонимы для документа: сначала сгенерированные по типу, иначе — рукописные."""
    if type_key:
        gen = _load_generated().get(type_key)
        if gen:
            return ' · '.join(gen)
    tl = title.lower()
    return ' '.join(a for k, a in DOC_ALIASES if k.lower() in tl)


def expand_query(q):
    ql = ' ' + q.lower().replace('ё', 'е') + ' '
    extra = [v for k, v in QUERY_SYN.items() if k in ql]
    return (q + ' ' + ' '.join(extra)).strip() if extra else q
